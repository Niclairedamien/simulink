    text(real(p1), imag(p1) + 400, ...
         sprintf(' Mode 1: %.0f Hz, \\zeta = %.3f', abs(p1)/(2*pi), -real(p1)/abs(p1)), ...
         'FontSize', 9, 'Color', [0.10 0.37 0.65], 'FontWeight','bold', ...
         'BackgroundColor','w', 'EdgeColor', [0.7 0.7 0.7], 'Margin', 3);
end
