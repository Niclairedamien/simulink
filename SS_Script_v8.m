%% 15. EXTENSION D: Linearisation error vs perturbation magnitude
%% ========================================================================
% Computes the linearisation error epsilon(d_hat) across the full range
% 0 < d_hat < 0.15, and identifies the 2% and 5% validity boundaries
% numerically.
%
% The linearisation error is defined as:
%   epsilon(d_hat) = ( V_C2_ss_linear - V_C2_ss_nonlinear ) / V_C2_ss_nonlinear
%
% where:
%   V_C2_ss_linear    = V_C2,0 + dcgain(sys_ss) * d_hat      (linear prediction)
%   V_C2_ss_nonlinear = ((1-2*(D0+d_hat))/(1-(D0+d_hat))) * V_g  (exact average)
%
% This is the analysis referenced by section 3.5.5 of the thesis chapter:
% the smooth growth of error across the validity boundary, with the three
% step-response studies (d_hat = 0.01, 0.05, 0.10) marked as data points
% on the curve.
%
% Output: Fig_3_7b_linearisation_error.png
%   (companion to the Simscape-generated Fig 3.7 which lives in
%   topology_Cslx.slx)
% ========================================================================
fprintf('\n===== EXTENSION D: Linearisation error sweep =====\n');
% Sweep range. Lower bound > 0 to avoid div-by-zero in the percent error.
d_hat_sweep = 0.001 : 0.001 : 0.150;
N_d = length(d_hat_sweep);
eps_pct = zeros(N_d, 1);    % linearisation error in percent
% DC gain of the linearised plant (computed once, used for all d_hat values)
G0 = dcgain(sys_ss);        % V/unit, expected to be approximately -832 V
for k = 1:N_d
    d_h = d_hat_sweep(k);
    % Linear prediction: small-signal Final-Value Theorem
    V_C2_linear = V_c2 + G0 * d_h;
    % Exact (averaged-model) nonlinear steady state at perturbed duty
    [Vo_k, ~, ~, ~, ~, ~] = operating_point(V_g, D0 + d_h, P_rated);
    eps_pct(k) = 100 * (V_C2_linear - Vo_k) / Vo_k;
end
% Locate the validity boundaries (where |error| crosses 2% and 5%)
abs_err = abs(eps_pct);
idx_2pct = find(abs_err >= 2.0, 1, 'first');
idx_5pct = find(abs_err >= 5.0, 1, 'first');
if ~isempty(idx_2pct)
    d_2pct = d_hat_sweep(idx_2pct);
    fprintf('   2%% validity boundary at d_hat = %.4f (%.1f%% of D0)\n', ...
            d_2pct, 100*d_2pct/D0);
else
    d_2pct = NaN;
end
if ~isempty(idx_5pct)
    d_5pct = d_hat_sweep(idx_5pct);
    fprintf('   5%% validity boundary at d_hat = %.4f (%.1f%% of D0)\n', ...
            d_5pct, 100*d_5pct/D0);
else
    d_5pct = NaN;
end
