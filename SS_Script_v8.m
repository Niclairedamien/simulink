    p2 = P_upper(2);
    text(real(p2), imag(p2) + 400, ...
         sprintf(' Mode 2: %.0f Hz, \\zeta = %.3f', abs(p2)/(2*pi), -real(p2)/abs(p2)), ...
         'FontSize', 9, 'Color', [0.75 0.25 0.10], 'FontWeight','bold', ...
         'BackgroundColor','w', 'EdgeColor', [0.7 0.7 0.7], 'Margin', 3);
end
drawnow;
print(gcf, 'Fig_3_8_pole_zero_map.png', '-dpng', '-r200');
fprintf('\n   Figure saved: Fig_3_8_pole_zero_map.png (200 dpi)\n');
