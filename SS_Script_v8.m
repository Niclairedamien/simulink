function [Vo, V_c1, V_c2, I_L1, I_L2, R] = operating_point(V_g, D, P_rated)
%OPERATING_POINT  Steady-state values of the semi-Z-source DC-DC converter.
%   Returns the output voltage, both capacitor voltages, both inductor
%   currents, and the equivalent load resistance for the averaged model,
%   evaluated at ANY duty ratio D (not just the linearisation point D0).
    Vo   = ((1 - 2*D)/(1 - D)) * V_g;
    V_c2 = Vo;
    V_c1 = ((1 - D)/D) * (V_g - Vo);
    R    = Vo^2 / P_rated;
    I_L2 = (Vo/R) * (D/(1 - D));
    I_L1 = ((1 - D)/D) * I_L2;
end
function [y, info, V_true] = run_step_study(sys_ss, V_c2_0, V_g, D0, ...
                                             d_hat, t, t_step, P_rated)
%RUN_STEP_STUDY  Run one step on the small-signal model and return the
%   deviation y, stepinfo struct, and nonlinear-steady-state target.
    u = d_hat * (t >= t_step);
    [y, ~] = lsim(sys_ss, u, t);
    info = stepinfo(y, t - t_step, y(end), ...
                    'SettlingTimeThreshold', 0.02);
    [Vo_new, ~, ~, ~, ~, ~] = operating_point(V_g, D0 + d_hat, P_rated);
    V_true = Vo_new;
    fprintf('   d_hat = %.3f\n', d_hat);
    fprintf('      Rise time         = %.3f ms\n', 1e3*info.RiseTime);
    fprintf('      Settling (2%%)    = %.3f ms\n', 1e3*info.SettlingTime);
    fprintf('      Overshoot         = %.2f %%\n', info.Overshoot);
    fprintf('      ss() final v_C2   = %.3f V\n', V_c2_0 + y(end));
    fprintf('      Nonlinear target  = %.3f V\n', V_true);
end
