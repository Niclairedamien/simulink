%  SS_Script_v8.m
%  ------------------------------------------------------------------------
%  Combined small-signal state-space driver for the Z-source DC-DC stage
%  of the semi-Z-source inverter (Chapter 3 of revised thesis).
%
%  CHANGE LOG v6 -> v7:
%    V_g updated from 400 V to 500 V to align with Chapter 6 decision
%    (ten PV panels in series at 50 V MPP each = 500 V PV-side DC bus,
%    giving M_nominal = 0.65 against the UK 230 V grid peak of 325.27 V).
%    All operating-point values, plant dynamics, and figures regenerate
%    automatically; the analytical structure of the script is unchanged.
%
%  CHANGE LOG v7 -> v8:
%    L1, L2 changed from 3 mH to 2 mH to match the Simulink simulation
%    model values. C1, C2 changed from 10 uF to 20 uF for the same reason.
%    Both pairs satisfy the inductor ripple and capacitor voltage-ripple
%    design constraints derived in S3.4 (verified numerically). All
%    operating-point values, plant dynamics, resonance frequencies,
%    damping ratios, and figures regenerate automatically.
%
%    Section 14 (L and C sensitivity sweep) sweep ranges were also
%    adjusted to centre on the new nominal values so the tolerance band
%    shading appears in the middle of the figure rather than at one edge.
%
%  This is the single canonical script for Chapter 3 simulation work.
%  It performs:
%    - Three step-response studies (Studies 1, 2, 3)
%    - Operating-point (D0) sensitivity sweep across the MPPT range
%    - Frequency-response analysis (Bode plot) at the nominal operating point
%
%  Each section addresses a specific examiner concern from the viva, and
%  the output figures are formatted for direct thesis inclusion (200 dpi,
%  proper annotations, clear legends).
%
%  ------------------------------------------------------------------------
%  Three step-response studies:
%
%    Study 1 - Small-signal validation (d_hat = 0.01)
%      Validates the linearised state-space model against the Simscape
%      switching model. Both should agree to within switching ripple.
%      Output: Fig_3_5_small_signal.png
%
%    Study 2 - Moderate-signal (d_hat = 0.05)
%      Demonstrates the boundary of the small-signal linearisation. At
%      this excitation the ss() prediction deviates from the true
%      nonlinear behaviour by a measurable amount.
%      Output: Fig_3_6_moderate_signal.png
%
%    Study 3 - Large-signal operating-point step (D: 0.2 -> 0.3)
%      The ss() model linearised about D0 = 0.2 is NOT VALID here and
%      must not be used; only the Simscape switching model can capture
%      this behaviour. The script prints the predicted new steady state
%      as a validation target.
%      Output: Fig_3_7_large_signal.png (generated by topology_Cslx.slx)
%
%  Plant-variation extensions:
%
%    Extension A - D0 sensitivity sweep (Section 12)
%      Rebuilds the small-signal model at 13 operating points from
%      D0 = 0.10 to 0.40. Extracts pole locations, damping ratios, and
%      DC gain at each. Establishes the analytical case for the
%      gain-scheduled PR controller of Chapter 6.
%      Output: Fig_3_10_D0_sweep.png
%
%    Extension B - Frequency response at D0 = 0.20 (Section 13)
%      Bode plot of the control-to-output transfer function Gvd(s).
%      Exposes the twin resonance peaks, partial pole-zero cancellation,
%      and bandwidth constraints for Chapter 6.
%      Output: Fig_3_9_bode.png
%
%  ------------------------------------------------------------------------
%  Naming convention preserved from v2:
%    'D0' in the main script = the operating-point duty ratio about which
%    the small-signal model is linearised. 'D' in local helper functions =
%    a generic duty-ratio argument that accepts D0, D0+d_hat, or D_new.
%
%  Author: Asi-Onob Usang Asi
%  ========================================================================
clear
