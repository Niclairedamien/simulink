% dominant-mode natural frequency, damping ratio, and DC gain at each D0.
%
% Purpose: provides the analytical justification for the gain-scheduled
% PR controller adopted in Chapter 6. A fixed-gain controller designed
% at a single D0 would not maintain consistent closed-loop performance
% across the MPPT operating range - this section quantifies the variation.
% ========================================================================
