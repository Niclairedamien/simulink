            zeta_mode2(k) = -real(P_cplx(idx2)) / abs(P_cplx(idx2));
        else
            fn_mode2(k) = NaN; zeta_mode2(k) = NaN;
        end
    else
        fn_mode1(k) = NaN; zeta_mode1(k) = NaN;
        fn_mode2(k) = NaN; zeta_mode2(k) = NaN;
    end
    dcgain_vec(k) = dcgain(sys_k);
    VC2_ss(k)     = V_c2_k;
