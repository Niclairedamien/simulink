%% ========================================================================
%% 1. Unified thesis parameter set (Chapters 3, 6, 7)
%% ========================================================================
V_g     = 500;                  % V    PV-side DC voltage (MPP)
                                %      Ten 50 V PV panels in series.
                                %      Updated from 400 V (v6) to align
                                %      with Chapter 6 modulation budget
                                %      (M_nominal = 325.27/500 = 0.65).
P_rated = 3000;                 % W    rated DC-DC output
D0      = 0.2;                  % -    operating-point duty ratio
Kd0     = 1 - D0;               % -    complement of D0
L1   = 2e-3;   L2   = 2e-3;     % H    Z-network inductance (v8: was 3 mH)
C1   = 20e-6;  C2   = 20e-6;    % F    Z-network capacitance (v8: was 10 uF)
r_L   = 50e-3;                  % Ohm  inductor DCR
R_on  = 100e-3;                 % Ohm  MOSFET on-resistance
V_F   = 1.0;                    % V    diode forward drop
r_C   = 20e-3;                  % Ohm  capacitor ESR (typical film cap)
r_L_eff = r_L + D0*R_on;        % Ohm  averaged inductor branch R at D0
% Capacitor ESR (r_C) is now included in the averaged model. At the dominant
% natural frequencies, the capacitor impedance |Z_C| ~ 20 Ohm is still three
% orders of magnitude larger than r_C ~ 20 mOhm, so the qualitative dynamics
% are unchanged. Pole locations shift by < 0.03 % and damping ratios shift
% by < 0.001 (analytical estimate verified numerically in this script).
% The inclusion serves methodological completeness rather than altering
% quantitative conclusions.
%% ========================================================================
%% 2. Steady-state operating point at D0 = 0.2
%% ========================================================================
[Vo, V_c1, V_c2, I_L1, I_L2, R] = operating_point(V_g, D0, P_rated);
fprintf('\n===== Operating point at D0 = %.3f =====\n', D0);
fprintf('   V_g     = %7.2f V\n',  V_g);
fprintf('   V_C1    = %7.2f V\n',  V_c1);
fprintf('   V_C2    = %7.2f V   (DC-bus output)\n',  V_c2);
fprintf('   I_L1    = %7.3f A\n',  I_L1);
fprintf('   I_L2    = %7.3f A\n',  I_L2);
fprintf('   R       = %7.2f Ohm (load for %d W)\n', R, P_rated);
fprintf('   r_L_eff = %.3f Ohm\n', r_L_eff);
%% ========================================================================
%% 3. Build the small-signal state-space model about D0 = 0.2
%% ========================================================================
% State x = [i_L1; i_L2; v_C1; v_C2];  input u = d_hat; output y = v_terminal,C2
%
% The model now includes capacitor ESR (r_C). With ESR, the voltage at the
% capacitor's external terminal is v_term = v_C + i_C*r_C, where v_C is the
% (ideal) capacitor state and i_C is the current flowing into the capacitor.
% This modification propagates two ways:
%   1. The inductor equations see the terminal voltages (vC1 + iC1*r_C) and
%      (vC2 + iC2*r_C) rather than vC1 and vC2 directly.
%   2. The output y is the voltage AT THE LOAD = v_terminal,C2, so the C
%      matrix is no longer [0 0 0 1] but has terms that depend on i_L1, i_L2.
%
% K_d_ind and K_d_cap arise from evaluating (A1 - A2)*X + (B1 - B2)*U at
% the operating point. The B vector is essentially unchanged by ESR (the
% ESR corrections to B are second-order in r_C/R ~ 7e-4).
% ------------------------------------------------------------------------
K_d_ind = V_c2 - V_c1 - V_g;
K_d_cap = I_L1 + I_L2;
% A matrix with capacitor ESR (full derivation in SS_ESR_Derivation.docx).
% Reduces to the original A when r_C = 0 (verified by cross-check).
%
% A[0,1] and A[1,0] are NEW entries (cross-coupling between iL1 and iL2)
% that appear only when r_C > 0. The on-diagonal inductor terms gain
% additional ESR-loss contributions. The load pole at A[3,3] shifts from
% -1/(R*C2) to -1/((R+r_C)*C2).
A = [ ( -R*r_C*(D0-1)^2 - (R+r_C)*(D0^2*r_C + r_L_eff) ) / (L1*(R+r_C)), ...
        -D0*r_C*(D0-1)*(2*R + r_C) / (L1*(R+r_C)), ...
        D0/L1, ...
        R*(D0-1) / (L1*(R+r_C)); ...
      -D0*r_C*(D0-1)*(2*R + r_C) / (L2*(R+r_C)), ...
       ( -D0^2*R*r_C - (R+r_C)*(r_C*(D0-1)^2 + r_L_eff) ) / (L2*(R+r_C)), ...
       (D0-1)/L2, ...
       D0*R / (L2*(R+r_C)); ...
      -D0/C1,  (1-D0)/C1,  0,  0; ...
       R*(1-D0)/(C2*(R+r_C)), ...
       -D0*R/(C2*(R+r_C)), ...
       0, ...
       -1/(C2*(R+r_C)) ];
B = [  K_d_ind/L1;  K_d_ind/L2;  -K_d_cap/C1;  -K_d_cap/C2 ];
% Output matrix C: y = v_terminal,C2 = vC2 + iC2*r_C, with the averaged
% iC2 expressed in terms of states. Reduces to [0 0 0 1] when r_C = 0.
Cm = [ R*r_C*(1-D0)/(R+r_C), ...
      -R*r_C*D0/(R+r_C), ...
       0, ...
       R/(R+r_C) ];
Dm = 0;
sys_ss = ss(A, B, Cm, Dm);
sys_ss.StateName  = {'i_L1','i_L2','v_C1','v_C2'};
sys_ss.InputName  = 'd_hat';
sys_ss.OutputName = 'v_C2_hat';
G_vd = tf(sys_ss);
%% ========================================================================
%% 4. Pole-zero analysis
%% ========================================================================
P_vec = pole(sys_ss);
fprintf('\n===== Pole-zero analysis =====\n');
for k = 1:length(P_vec)
    s = P_vec(k);
    if abs(imag(s)) < 1e-6
        fprintf('   s_%d = %+10.4e          (real)\n', k, real(s));
    else
        wn = abs(s); zeta = -real(s)/wn;
        fprintf('   s_%d = %+10.4e %+8.4ej   wn = %.1f rad/s (%.1f Hz), zeta = %.4f\n', ...
                k, real(s), imag(s), wn, wn/(2*pi), zeta);
    end
end
% --- Figure 3.8: pole-zero map ----------------------------------------
% Visualisation of the four poles and three zeros of Gvd(s) on the s-plane.
% Use MATLAB's built-in pzmap which handles axis scaling automatically.
figure('Color','w','Position',[140 140 800 700]);
pzmap(sys_ss);
grid on; box on;
title('Figure 3.8 - Pole-zero map of G_{vd}(s) at D_0 = 0.20', ...
      'FontSize', 13, 'FontWeight','bold');
xlabel('Real axis (rad/s)', 'FontSize', 11);
ylabel('Imaginary axis (rad/s)', 'FontSize', 11);
set(gca, 'FontSize', 10);
% Annotate the modes (find pole pairs and label them)
P_complex = P_vec(abs(imag(P_vec)) > 1e-6);
P_upper   = P_complex(imag(P_complex) > 0);   % upper-half-plane representatives
[~, sort_idx] = sort(abs(P_upper));
P_upper = P_upper(sort_idx);
