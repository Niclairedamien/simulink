fn_mode1   = zeros(N_sweep, 1);
zeta_mode1 = zeros(N_sweep, 1);
fn_mode2   = zeros(N_sweep, 1);
zeta_mode2 = zeros(N_sweep, 1);
n_complex  = zeros(N_sweep, 1);
dcgain_vec = zeros(N_sweep, 1);
VC2_ss     = zeros(N_sweep, 1);
ts_2pct    = zeros(N_sweep, 1);
for k = 1:N_sweep
    D0_k  = D0_sweep(k);
    Kd0_k = 1 - D0_k;
    [~, V_c1_k, V_c2_k, I_L1_k, I_L2_k, R_k] = operating_point(V_g, D0_k, P_rated);
    r_L_eff_k = r_L + D0_k * R_on;
    K_d_ind_k = V_c2_k - V_c1_k - V_g;
    K_d_cap_k = I_L1_k + I_L2_k;
    % A matrix with capacitor ESR (same form as Section 3)
    A_k = [ ( -R_k*r_C*(D0_k-1)^2 - (R_k+r_C)*(D0_k^2*r_C + r_L_eff_k) ) / (L1*(R_k+r_C)), ...
              -D0_k*r_C*(D0_k-1)*(2*R_k + r_C) / (L1*(R_k+r_C)), ...
              D0_k/L1, ...
              R_k*(D0_k-1) / (L1*(R_k+r_C)); ...
            -D0_k*r_C*(D0_k-1)*(2*R_k + r_C) / (L2*(R_k+r_C)), ...
             ( -D0_k^2*R_k*r_C - (R_k+r_C)*(r_C*(D0_k-1)^2 + r_L_eff_k) ) / (L2*(R_k+r_C)), ...
             (D0_k-1)/L2, ...
             D0_k*R_k / (L2*(R_k+r_C)); ...
            -D0_k/C1,  (1-D0_k)/C1,  0,  0; ...
             R_k*(1-D0_k)/(C2*(R_k+r_C)), ...
             -D0_k*R_k/(C2*(R_k+r_C)), ...
             0, ...
             -1/(C2*(R_k+r_C)) ];
    B_k = [ K_d_ind_k/L1; K_d_ind_k/L2; -K_d_cap_k/C1; -K_d_cap_k/C2 ];
    % Output matrix C with ESR
    Cm_k = [ R_k*r_C*(1-D0_k)/(R_k+r_C), ...
            -R_k*r_C*D0_k/(R_k+r_C), ...
             0, ...
             R_k/(R_k+r_C) ];
